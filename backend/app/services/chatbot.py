import time
from dataclasses import dataclass, field
from typing import Optional

from backend.app.config import settings
from backend.app.schemas import EntityItem
from backend.app.services.entity_extractor import entity_extractor
from backend.app.services.fuzzy_router import fuzzy_router
from backend.app.services.intent_classifier import intent_classifier
from backend.app.services.preprocessing import preprocess
from backend.app.services.response_engine import response_engine
from backend.app.services.semantic_similarity import semantic_similarity_engine


@dataclass
class ChatbotResult:
    """Full internal result generated by the Layer 1 NLP pipeline and Fuzzy Router."""

    response: str
    layer: str
    intent: str
    confidence: float
    entities: list[EntityItem]
    similarity_score: float
    matched_pattern: str
    complexity_score: float
    entity_density: float
    activation_score: float
    routing_reason: str
    fallback: bool
    processing_time_ms: float
    fired_rules: list[str] = field(default_factory=list)


class ChatbotService:
    """
    Core ChatLab NLP Orchestrator with Mamdani Fuzzy Logic Decision Router.
    Coordinates preprocessing, intent classification, named entity recognition,
    semantic similarity scoring, fuzzy logic inference, and response dispatching.
    """

    def __init__(self) -> None:
        self.confidence_threshold = settings.LAYER1_CONFIDENCE_THRESHOLD
        self.similarity_threshold = settings.SEMANTIC_SIMILARITY_THRESHOLD

    def process(self, message: str, session_id: Optional[str] = None) -> ChatbotResult:
        """
        Executes end-to-end NLP & Fuzzy Routing pipeline for an incoming user utterance.
        """
        start_time = time.perf_counter()

        # 1. Text Preprocessing
        preprocessed = preprocess(message)

        # 2. Intent Classification via ML model
        prediction = intent_classifier.predict(message)
        primary_intent = prediction.intent
        confidence = prediction.confidence

        # 3. Entity Extraction
        entities = entity_extractor.extract_entities(message)

        # 4. Semantic Similarity Matching
        similarity = semantic_similarity_engine.find_best_match(message)

        # Reconcile primary intent if semantic match is strong and classifier is unsure
        resolved_intent = primary_intent
        if confidence < self.confidence_threshold and similarity.score >= self.similarity_threshold:
            if similarity.matched_intent and similarity.matched_intent != "unknown":
                resolved_intent = similarity.matched_intent

        # 5. Derive Query Complexity and Entity Density for Soft Computing Router
        complexity = fuzzy_router.compute_query_complexity(message, preprocessed)
        entity_density = fuzzy_router.compute_entity_density(entities, preprocessed)

        # 6. Mamdani Fuzzy Inference Routing Decision
        fuzzy_decision = fuzzy_router.route(
            confidence=confidence,
            similarity=similarity.score,
            complexity=complexity,
            entity_density=entity_density,
            intent=resolved_intent,
        )

        # 7. Response Generation
        if fuzzy_decision.is_fallback:
            reply_text = settings.FALLBACK_RESPONSE
        else:
            reply_text = response_engine.get_response(resolved_intent, fallback=False)

        elapsed_ms = round((time.perf_counter() - start_time) * 1000, 2)

        return ChatbotResult(
            response=reply_text,
            layer=fuzzy_decision.selected_layer,
            intent=resolved_intent,
            confidence=confidence,
            entities=entities,
            similarity_score=similarity.score,
            matched_pattern=similarity.matched_pattern,
            complexity_score=complexity,
            entity_density=entity_density,
            activation_score=fuzzy_decision.activation_score,
            routing_reason=fuzzy_decision.reason,
            fallback=fuzzy_decision.is_fallback,
            processing_time_ms=elapsed_ms,
            fired_rules=fuzzy_decision.fired_rules,
        )


# Global singleton instance reused across requests
chatbot_service = ChatbotService()
